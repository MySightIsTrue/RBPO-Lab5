CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE CHECK (length(trim(username)) > 0),
    email VARCHAR(255) NOT NULL UNIQUE CHECK (length(trim(email)) > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE translation_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL CHECK (length(trim(name)) > 0),
    target_language VARCHAR(255) NOT NULL CHECK (length(trim(target_language)) > 0),
    owner_id BIGINT NOT NULL REFERENCES app_users(id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT', 'IN_PROGRESS', 'COMPLETED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE source_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES translation_projects(id) ON DELETE CASCADE,
    source_text TEXT NOT NULL CHECK (length(trim(source_text)) > 0),
    segment_order INTEGER NOT NULL CHECK (segment_order > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (project_id, segment_order)
);
CREATE TABLE translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id BIGINT NOT NULL REFERENCES source_segments(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES app_users(id),
    text TEXT NOT NULL CHECK (length(trim(text)) > 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT', 'SUBMITTED', 'REVISION', 'APPROVED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE editorial_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    translation_id BIGINT NOT NULL REFERENCES translations(id) ON DELETE CASCADE,
    comment_text TEXT NOT NULL CHECK (length(trim(comment_text)) > 0),
    resolution_status VARCHAR(30) NOT NULL CHECK (resolution_status IN ('OPEN', 'RESOLVED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_projects_owner ON translation_projects(owner_id);
CREATE INDEX idx_translations_segment ON translations(segment_id);
CREATE INDEX idx_translations_author ON translations(author_id);
CREATE INDEX idx_comments_translation ON editorial_comments(translation_id);
